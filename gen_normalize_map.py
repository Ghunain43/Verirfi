"""Turns shared/normalize_map.json into mobile/lib/normalize_map.g.dart.

Run from anywhere:   python mobile/tool/gen_normalize_map.py
Re-run it whenever Sharjeel changes shared/normalize_map.json. The test in
mobile/test/fingerprint_test.dart fails if the generated file is out of date.
"""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
src = root / "shared" / "normalize_map.json"
dst = root / "mobile" / "lib" / "normalize_map.g.dart"

text = src.read_text(encoding="utf-8")
data = json.loads(text)  # validates the JSON
for key in ("char_map", "roman_urdu"):
    if key not in data:
        sys.exit("normalize_map.json is missing the key: " + key)
if "'''" in text:
    sys.exit("normalize_map.json contains three single quotes in a row; cannot embed it")

header = (
    "// GENERATED by mobile/tool/gen_normalize_map.py from shared/normalize_map.json.\n"
    "// Do not edit by hand. Re-run the script when the shared file changes.\n\n"
)
dst.write_text(
    header + "const String kNormalizeMapJson = r'''" + text + "''';\n",
    encoding="utf-8",
)
print("wrote", dst, "(", len(data["char_map"]), "char_map entries,", len(data["roman_urdu"]), "roman_urdu entries )")
